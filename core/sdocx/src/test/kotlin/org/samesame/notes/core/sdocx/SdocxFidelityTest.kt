    }

    // ---- helpers ----

    /** Recomputes every derived hash from the spec formulas and checks the embedded values. */
    private fun assertHashesConsistent(archive: SdocxArchive, entries: Map<String, ByteArray>) {
        val noteBytes = entries.getValue("note.note")
        val docHash = noteBytes.copyOfRange(noteBytes.size - 32, noteBytes.size)
        assertThat(sha256(noteBytes.copyOfRange(0, noteBytes.size - 32))).isEqualTo(docHash)
        assertThat(archive.note.docHash).isEqualTo(docHash)

        assertThat(entries.getValue("pageIdInfo.dat").copyOfRange(0, 32)).isEqualTo(docHash)
        assertThat(archive.pageIdInfo.docHash).isEqualTo(docHash)

        val computedPageHashes = ArrayList<ByteArray>()
        for (page in archive.pages) {
            val layerHashes = page.layers.map { layer ->
                // A container's own hash is followed by its children's hashes (spec §7).
                val objectHashes = layer.objects.flatMap { objectHashesOf(it) }
                sha256(concat(objectHashes) + sha256("${layer.layerId}${layer.modifiedTime}"))
            }
            val pageHash = sha256(concat(layerHashes) + sha256("${page.pageId}${page.modifiedTime}"))
            assertThat(page.originalHash).isEqualTo(pageHash)
            computedPageHashes += pageHash

            val pageBytes = entries.getValue("${page.pageId}.page")
            assertThat(pageBytes.copyOfRange(pageBytes.size - 58, pageBytes.size - 26)).isEqualTo(pageHash)
        }

        assertThat(archive.pageIdInfo.pages).hasSize(computedPageHashes.size)
        for (index in archive.pageIdInfo.pages.indices) {
            // ByteArray has identity equality, so compare each hash through the array subject.
            assertThat(archive.pageIdInfo.pages[index].pageHash).isEqualTo(computedPageHashes[index])
            assertThat(archive.pageIdInfo.pages[index].pageId).isEqualTo(archive.pages[index].pageId)
        }
    }

    /** The object's change token followed by every child's, matching the layer-hash input order. */
    private fun objectHashesOf(obj: org.samesame.notes.core.sdocx.record.ObjectEntry): List<ByteArray> {
        val own = if (obj.uuid != null) objectHash(obj.uuid, obj.modifiedTime!!) else obj.originalHash
        return listOf(own) + obj.children.flatMap { objectHashesOf(it) }
    }

    /** Patches the base block's `modifiedTime` (offset 60 in every object base) and its identity. */
    private fun org.samesame.notes.core.sdocx.record.ObjectEntry.withBaseModifiedTime(modifiedUs: Long):
        org.samesame.notes.core.sdocx.record.ObjectEntry {
        val patched = record.copyOf()
        for (i in 0 until 8) {
            patched[60 + i] = ((modifiedUs ushr (8 * i)) and 0xFF).toByte()
        }
        return org.samesame.notes.core.sdocx.record.ObjectEntry(
            objectType = objectType,
            childCount = childCount,
            record = patched,
            originalHash = originalHash,
            uuid = uuid,
            modifiedTime = modifiedUs,
            children = children,
        )
    }

    private fun assertEntriesEqual(actual: Map<String, ByteArray>, expected: Map<String, ByteArray>) {
        assertThat(actual.keys).isEqualTo(expected.keys)
        for ((name, expectedBytes) in expected) {
            assertThat(actual.getValue(name)).isEqualTo(expectedBytes)
        }
    }

    private fun zipEntries(bytes: ByteArray): Map<String, ByteArray> {
        val out = LinkedHashMap<String, ByteArray>()
        ZipInputStream(ByteArrayInputStream(bytes)).use { zip ->
            while (true) {
                val entry = zip.nextEntry ?: break
                out[entry.name] = zip.readBytes()
                zip.closeEntry()
            }
        }
        return out
    }
