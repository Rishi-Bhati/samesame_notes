package org.samesame.notes.core.sdocx

import com.google.common.truth.Truth.assertThat
import org.junit.Test
import org.samesame.notes.core.model.richtext.RichText
import org.samesame.notes.core.sdocx.map.SdocxMapper
import org.samesame.notes.core.sdocx.record.LayerRecord
import org.samesame.notes.core.sdocx.record.PageRecord
import java.io.ByteArrayInputStream
import java.util.zip.ZipInputStream

/**
 * Round-trip fidelity checks for the rich fixture: every object kind, two pages, an extended media
 * registry, an end tag without the fixed-font group and unknown text spans/paragraphs.
 *
 * The fixture is generated by [SdocxWriter] itself, never copied from a device note. The independent
 * inspector runs only when `SAMESAME_SDOCX_INSPECTOR` points at it (see `SdocxInspectorTest`).
 */
class SdocxFidelityTest {

    private fun writer() = SdocxWriter()
    private fun reader() = SdocxReader()

    private fun firstBytes(
        pageMode: Int = SdocxFormat.PageMode.LIST,
        locked: Boolean = false,
        extendedMedia: Boolean = true,
        hasFixedFontGroup: Boolean = false,
        hasTail: Boolean = true,
    ): ByteArray = writer().writeToBytes(
        SdocxFixtures.richArchive(
            pageMode = pageMode,
            locked = locked,
            extendedMedia = extendedMedia,
            hasFixedFontGroup = hasFixedFontGroup,
            hasTail = hasTail,
        ),
    )

    // ---- no-edit stability ----

    @Test
    fun `rich fixture writer reader writer is byte identical`() {
        for (hasFixedFontGroup in listOf(false, true)) {
            val first = firstBytes(hasFixedFontGroup = hasFixedFontGroup)
            val second = writer().writeToBytes(reader().read(first))
            assertThat(second).isEqualTo(first)
        }
    }

    @Test
    fun `rich fixture round trip keeps every zip entry identical`() {
        val first = firstBytes()
        val second = writer().writeToBytes(reader().read(first))
        assertEntriesEqual(zipEntries(second), zipEntries(first))
    }

    @Test
    fun `rich fixture parses every object kind and keeps unknown records`() {
        val archive = reader().read(firstBytes())
        assertThat(archive.pages).hasSize(2)

        val objects = archive.pages[0].layers[0].objects
        assertThat(objects.map { it.objectType }).containsExactly(
            SdocxFormat.ObjectType.STROKE,
            SdocxFormat.ObjectType.IMAGE,
            SdocxFormat.ObjectType.TEXT_BOX,
            SdocxFormat.ObjectType.VOICE,
            9,
            SdocxFormat.ObjectType.CONTAINER,
        ).inOrder()

        val unknown = objects[4]
        assertThat(unknown.record).isEqualTo(SdocxFixtures.baseBlock(SdocxFixtures.UUID_UNKNOWN, SdocxFixtures.MODIFIED_US))

        val container = objects[5]
        assertThat(container.children).hasSize(1)
        assertThat(container.children[0].objectType).isEqualTo(SdocxFormat.ObjectType.STROKE)
        assertThat(container.children[0].record).isEqualTo(
            SdocxFixtures.strokeRecord(SdocxFixtures.UUID_CHILD, SdocxFixtures.MODIFIED_US),
        )

        assertThat(archive.extraEntries.getValue("extra/keep.bin")).isEqualTo(byteArrayOf(9, 8, 7))
    }

    @Test
    fun `doc page layer and object hashes are consistent after a rich round trip`() {
        val bytes = firstBytes()
        val archive = reader().read(bytes)
        assertHashesConsistent(archive, zipEntries(bytes))
    }

    // ---- one-unit edits ----

    @Test
    fun `text edit leaves every page entry byte identical and recomputes the doc hash`() {
        val first = firstBytes()
        val archive = reader().read(first)
        val document = SdocxMapper.toNoteDocument(archive, noteId = "note-x")
        val newBody = document.body.text + "!"
        val edited = document.copy(
            title = "Edited title",
            body = RichText.of(newBody),
        )

        val second = writer().writeToBytes(
            SdocxMapper.applyDocumentEdits(archive, edited, nowUs = SdocxFixtures.MODIFIED_US + 5_000L),
        )
        val before = zipEntries(first)
        val after = zipEntries(second)

        assertThat(after.keys).isEqualTo(before.keys)
        for (page in archive.pages) {
            assertThat(after.getValue("${page.pageId}.page"))
                .isEqualTo(before.getValue("${page.pageId}.page"))
        }
        assertThat(after.getValue("media/mediaInfo.dat"))
            .isEqualTo(before.getValue("media/mediaInfo.dat"))
        assertThat(after.getValue("note.note")).isNotEqualTo(before.getValue("note.note"))

        val restored = reader().read(second)
        assertHashesConsistent(restored, after)
        assertThat(restored.note.title.text?.text).isEqualTo("Edited title")
        assertThat(restored.note.body.text?.text).isEqualTo(newBody)
        // The imported note identity is the source note's, not a SameSame id.
        assertThat(restored.note.noteId).isEqualTo(archive.note.noteId)
        assertThat(restored.endTag.noteId).isEqualTo(archive.note.noteId)
        assertThat(restored.note.fileRevision).isEqualTo(archive.note.fileRevision + 1)
    }

    @Test
    fun `editing one object leaves the other objects and the other page byte identical`() {
        val first = firstBytes()
        val archive = reader().read(first)
        val page = archive.pages[0]
        val layer = page.layers[0]
        // A real object edit rewrites the base block's modified time too, so the hash the writer
        // derives and the one the reader parses from the record agree.
        val changedStroke = layer.objects[0].withBaseModifiedTime(SdocxFixtures.MODIFIED_US + 1)
        val changedLayer = LayerRecord(
            flags = layer.flags,
            optMask = layer.optMask,
            layerNumber = layer.layerNumber,
            optionalRaw = layer.optionalRaw,
            objects = listOf(changedStroke) + layer.objects.drop(1),
            originalHash = layer.originalHash,
            layerId = layer.layerId,
            modifiedTime = layer.modifiedTime,
        )
        val changedPage = PageRecord(
            orientation = page.orientation,
            width = page.width,
            height = page.height,
            offsetX = page.offsetX,
            offsetY = page.offsetY,
            pageId = page.pageId,
            modifiedTime = page.modifiedTime,
            formatVersion = page.formatVersion,
            minFormatVersion = page.minFormatVersion,
            pageFlags = page.pageFlags,
            propMask = page.propMask,
            properties = page.properties,
            layers = listOf(changedLayer),
            originalHash = page.originalHash,
            currentLayerIndex = page.currentLayerIndex,
        )
        val edited = SdocxArchive(
            endTag = archive.endTag,
            note = archive.note,
            pageIdInfo = archive.pageIdInfo,
            pages = listOf(changedPage, archive.pages[1]),
            media = archive.media,
            mediaFiles = archive.mediaFiles,
            extraEntries = archive.extraEntries,
        )

        val second = writer().writeToBytes(edited)
        val before = zipEntries(first)
        val after = zipEntries(second)
        // The untouched page file is byte-identical; only the edited page is rewritten.
        assertThat(after.getValue("${archive.pages[1].pageId}.page"))
            .isEqualTo(before.getValue("${archive.pages[1].pageId}.page"))
        assertThat(after.getValue("${page.pageId}.page"))
            .isNotEqualTo(before.getValue("${page.pageId}.page"))

        val restored = reader().read(second)
        assertHashesConsistent(restored, after)
        val reObjects = restored.pages[0].layers[0].objects
        val originalObjects = archive.pages[0].layers[0].objects
        assertThat(reObjects).hasSize(originalObjects.size)
        // Only the edited object's change token changed; every other record and hash is reused.
        for (index in 1 until originalObjects.size) {
            assertThat(reObjects[index].record).isEqualTo(originalObjects[index].record)
            assertThat(reObjects[index].originalHash).isEqualTo(originalObjects[index].originalHash)
        }
        assertThat(reObjects[0].record).isEqualTo(changedStroke.record)
        assertThat(reObjects[0].originalHash)
            .isEqualTo(objectHash(SdocxFixtures.UUID_STROKE, SdocxFixtures.MODIFIED_US + 1))
        assertThat(reObjects[0].originalHash).isNotEqualTo(originalObjects[0].originalHash)
    }

    @Test
    fun `text edit re-anchors unknown spans paragraphs and inline objects`() {
        val archive = reader().read(firstBytes())
        val document = SdocxMapper.toNoteDocument(archive, noteId = "n")
        val newBody = document.body.text + "!"
        val edited = SdocxMapper.applyDocumentEdits(
            archive,
            document.copy(body = RichText.of(newBody)),
            nowUs = SdocxFixtures.MODIFIED_US + 1_000L,
        )
        val restored = reader().read(writer().writeToBytes(edited))
        val tc = restored.note.body.text!!

        assertThat(tc.text).isEqualTo(newBody)
        assertThat(tc.spans.map { it.kind }).contains(4) // fontName
        assertThat(tc.spans.map { it.kind }).contains(9) // hyperText
        assertThat(tc.paragraphs.map { it.kind }).contains(4) // line spacing
        assertThat(tc.marginLeft).isEqualTo(16f)
        assertThat(tc.marginTop).isEqualTo(10f)
        assertThat(tc.marginRight).isEqualTo(16f)
        assertThat(tc.marginBottom).isEqualTo(10f)
        assertThat(tc.tailFlags).isEqualTo(1)

        // Appending to the end leaves every anchor offset unchanged.
        val fontName = tc.spans.first { it.kind == 4 }
        assertThat(fontName.start).isEqualTo(0)
        assertThat(fontName.end).isEqualTo(4)
        val hyperlink = tc.spans.first { it.kind == 9 }
        assertThat(hyperlink.start).isEqualTo(11)
        assertThat(hyperlink.end).isEqualTo(17)

        assertThat(tc.objectSpans).hasSize(1)
        assertThat(tc.objectSpans[0].objectType).isEqualTo(SdocxFormat.ObjectType.IMAGE)
        assertThat(tc.objectSpans[0].charPos).isEqualTo(5)
        assertThat(tc.objectSpans[0].record).isEqualTo(
            SdocxFixtures.imageObjectRecord(SdocxFixtures.INLINE_IMAGE_UUID, SdocxFixtures.MODIFIED_US, 400.0, 300.0, 0),
        )
    }

    // ---- end tag / media variants ----

    @Test
    fun `end tag fixed-font group is written only when the source had it`() {
        val without = reader().read(firstBytes(hasFixedFontGroup = false))
        assertThat(without.endTag.hasTail).isTrue()
        assertThat(without.endTag.hasFixedFontGroup).isFalse()

        val with = reader().read(firstBytes(hasFixedFontGroup = true))
        assertThat(with.endTag.hasTail).isTrue()
        assertThat(with.endTag.hasFixedFontGroup).isTrue()
    }

    @Test
    fun `end tag without the optional tail round trips`() {
        val bytes = firstBytes(hasTail = false)
        val archive = reader().read(bytes)
        assertThat(archive.endTag.hasTail).isFalse()
        assertThat(archive.endTag.hasFixedFontGroup).isFalse()
        assertThat(archive.endTag.documentType).isEqualTo(SdocxFormat.DocumentType.UNLOCKED)
        assertThat(writer().writeToBytes(archive)).isEqualTo(bytes)
    }

    @Test
    fun `extended media entries keep their unknown extension bytes and terminator`() {
        val archive = reader().read(firstBytes(extendedMedia = true))
        assertThat(archive.media.extended).isTrue()
        assertThat(archive.media.hasTerminator).isTrue()
        assertThat(archive.media.entries[0].extra).isEqualTo(byteArrayOf(0x55, 0x66, 0x77))
        assertThat(archive.media.entries[1].extra).isEqualTo(byteArrayOf(0x11))
        assertThat(archive.media.entries[0].isFileAttached).isTrue()

        // The basic form keeps its source form and never gains an EOFX tail.
        val basic = reader().read(firstBytes(extendedMedia = false))
        assertThat(basic.media.extended).isFalse()
        assertThat(basic.media.entries[0].isFileAttached).isNull()
        assertThat(basic.media.entries[0].extra).isEmpty()
        assertThat(writer().writeToBytes(basic)).isEqualTo(firstBytes(extendedMedia = false))
    }

    // ---- note/end-tag mirroring ----

    @Test
    fun `voice edit bumps note and end tag stamps and keeps the source note id`() {
        val archive = reader().read(firstBytes())
        val recording = SdocxMapper.toNoteDocument(archive, "n").recordings.single()
        val now = SdocxFixtures.MODIFIED_US + 1_000_000L
        val edited = SdocxVoiceList.apply(
            archive,
            listOf(recording.copy(name = "Renamed")),
            nowUs = now,
            audio = { null },
        )

        assertThat(edited.note.modifiedTime).isEqualTo(now)
        assertThat(edited.note.noteId).isEqualTo(archive.note.noteId)
        assertThat(edited.endTag.modifiedTime).isEqualTo(now)
        assertThat(edited.endTag.displayModifiedTime).isEqualTo(now)
        assertThat(edited.endTag.noteId).isEqualTo(archive.note.noteId)

        val restored = reader().read(writer().writeToBytes(edited))
        assertHashesConsistent(restored, zipEntries(writer().writeToBytes(edited)))
        val voice = restored.note.properties.voiceData!!.single()
        assertThat(voice.name).isEqualTo("Renamed")
        assertThat(voice.recordingTime).isEqualTo(12_000L)
        assertThat(restored.endTag.modifiedTime).isEqualTo(now)
    }

    @Test
    fun `page image fallback bumps page layer and end tag stamps`() {
        val archive = reader().read(firstBytes())
        val page = archive.pages[1]
        val now = SdocxFixtures.MODIFIED_US + 2_000_000L
        val edited = SdocxPageImageFallback.apply(
            archive,
            pageImages = mapOf(page.pageId to byteArrayOf(1, 2, 3, 4)),
            newUuid = { "12121212-1212-1212-1212-121212121212" },
            nowUs = { now },
        )

        assertThat(edited.pages[0].modifiedTime).isEqualTo(archive.pages[0].modifiedTime)
        assertThat(edited.pages[1].modifiedTime).isEqualTo(now)
        assertThat(edited.pages[1].layers[0].modifiedTime).isEqualTo(now)
        assertThat(edited.note.modifiedTime).isEqualTo(now)
        assertThat(edited.endTag.modifiedTime).isEqualTo(now)
        assertThat(edited.endTag.noteId).isEqualTo(archive.note.noteId)
        assertThat(edited.media.entries.last().fileName).isEqualTo("page-${page.pageId}.png")
        assertThat(edited.mediaFiles).containsKey("media/page-${page.pageId}.png")

        val newObjects = edited.pages[1].layers[0].objects
        assertThat(newObjects).hasSize(page.layers[0].objects.size + 1)
        assertThat(newObjects.first().record).isEqualTo(page.layers[0].objects.first().record)
        assertThat(newObjects.last().objectType).isEqualTo(SdocxFormat.ObjectType.IMAGE)

        val bytes = writer().writeToBytes(edited)
        val restored = reader().read(bytes)
        assertHashesConsistent(restored, zipEntries(bytes))
        // The untouched first page file is byte-identical to the source export.
        val sourceEntries = zipEntries(firstBytes())
        assertThat(zipEntries(bytes).getValue("${archive.pages[0].pageId}.page"))
            .isEqualTo(sourceEntries.getValue("${archive.pages[0].pageId}.page"))
    }

    @Test
    fun `view position update rewrites only end tag and keeps the note stamp`() {
        val archive = reader().read(firstBytes())
        val document = SdocxMapper.toNoteDocument(archive, "n")

        val unchanged = SdocxMapper.applyDocumentEdits(
            archive, document, nowUs = SdocxFixtures.MODIFIED_US, lastViewedPageIndex = 0,
        )
        assertThat(unchanged).isSameInstanceAs(archive)

        val edited = SdocxMapper.applyDocumentEdits(
            archive, document, nowUs = SdocxFixtures.MODIFIED_US, lastViewedPageIndex = 1,
        )
        assertThat(edited.endTag.lastViewedPageIndex).isEqualTo(1)
        assertThat(edited.note.modifiedTime).isEqualTo(archive.note.modifiedTime)

        val before = zipEntries(writer().writeToBytes(archive))
        val after = zipEntries(writer().writeToBytes(edited))
        assertThat(after.getValue("note.note")).isEqualTo(before.getValue("note.note"))
        assertThat(after.getValue("pageIdInfo.dat")).isEqualTo(before.getValue("pageIdInfo.dat"))
        for (page in archive.pages) {
            assertThat(after.getValue("${page.pageId}.page"))
                .isEqualTo(before.getValue("${page.pageId}.page"))
        }
        assertThat(after.getValue("end_tag.bin")).isNotEqualTo(before.getValue("end_tag.bin"))
        assertThat(reader().read(writer().writeToBytes(edited)).endTag.lastViewedPageIndex).isEqualTo(1)
    }

    @Test
    fun `locked rich note keeps its flag and owner across an edited export`() {
