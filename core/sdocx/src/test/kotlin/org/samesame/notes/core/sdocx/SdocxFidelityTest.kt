    @Test
    fun `imported page mode survives a text edit`() {
        for (mode in listOf(SdocxFormat.PageMode.LIST, SdocxFormat.PageMode.SINGLE)) {
            val archive = reader().read(firstBytes(pageMode = mode))
            val document = SdocxMapper.toNoteDocument(archive, "n")
            val edited = SdocxMapper.applyDocumentEdits(
