package org.samesame.notes.core.model

import kotlin.math.roundToInt

/** Parts of the app whose text size can be scaled on its own, on top of the app-wide scale. */
enum class FontSection {
    /** Notes list / home: titles, previews, dates. */
    Notes,

    /** Editor: only the default size of NEW text (saved notes keep their own sizes). */
    Editor,

    /** Toolbars and menus. */
    Chrome,

    /** The Files screens. */
    Files,

    /** The navigation drawer. */
    Drawer,
}

/** What font the UI (and note text with no font of its own) uses. */
enum class FontKind { System, Bundled, Custom }

/** The chosen font: [bundledId] is a [BundledFonts] id when [kind] is [FontKind.Bundled]. */
data class FontChoice(val kind: FontKind = FontKind.System, val bundledId: String? = null) {
    /** Stored form: `system`, `bundled:<id>` or `custom`. */
    fun serialize(): String = when (kind) {
        FontKind.System -> "system"
        FontKind.Bundled -> "bundled:$bundledId"
        FontKind.Custom -> "custom"
    }

    companion object {
        /** Unknown or malformed values read as System default. */
        fun parse(raw: String?): FontChoice = when {
            raw == "custom" -> FontChoice(FontKind.Custom)
            raw != null && raw.startsWith("bundled:") && raw.removePrefix("bundled:") in BundledFonts.ids ->
                FontChoice(FontKind.Bundled, raw.removePrefix("bundled:"))
            else -> FontChoice()
        }
    }
}

/** Ids of the fonts that ship with the app (the files live in the design system). */
object BundledFonts {
    const val ATKINSON = "atkinson_hyperlegible"
    const val PLEX_SERIF = "ibm_plex_serif"
    val ids: List<String> = listOf(ATKINSON, PLEX_SERIF)
}

/**
 * Font size and style. Scales are whole percents: the app-wide [appPercent] multiplies the section's own percent
 * (each 85..150 in steps of 5, 100 = unchanged).
 */
data class FontSettings(
    val appPercent: Int = FontScaling.DEFAULT,
    val sectionPercent: Map<FontSection, Int> = emptyMap(),
    val choice: FontChoice = FontChoice(),
    /** Display name of the added font file, kept for the settings row; the file itself is in the app's private storage. */
    val customFontName: String? = null,
    /** Private storage name; null keeps custom fonts imported before versioned filenames. */
    val customFontFileName: String? = null,
) {
    fun section(section: FontSection): Int = FontScaling.clamp(sectionPercent[section] ?: FontScaling.DEFAULT)

    /** Multiplier for the text of [section]: app-wide times section. */
    fun scaleFor(section: FontSection): Float = FontScaling.effective(appPercent, section(section))

    /** Whether any size differs from the default (enables "Reset to default"). */
    val sizesChanged: Boolean
        get() = FontScaling.clamp(appPercent) != FontScaling.DEFAULT || sectionPercent.values.any { FontScaling.clamp(it) != FontScaling.DEFAULT }

    /** Size of text typed into an empty note (null = the normal default, nothing to set). Whole points like the size menu. */
    fun newTextSize(): Float? {
        val size = (Limits.DEFAULT_FONT_SIZE * scaleFor(FontSection.Editor)).roundToInt().toFloat()
        return if (size == Limits.DEFAULT_FONT_SIZE) null else size
    }
}

/** The scale math behind Settings > Font size. */
object FontScaling {
    const val MIN = 85
    const val MAX = 150
    const val STEP = 5
    const val DEFAULT = 100

    /** Nearest allowed percent: clamped to [MIN]..[MAX] and snapped to [STEP]. */
    fun clamp(percent: Int): Int = (percent.coerceIn(MIN, MAX) / STEP.toFloat()).roundToInt() * STEP

    fun effective(appPercent: Int, sectionPercent: Int): Float = clamp(appPercent) / 100f * (clamp(sectionPercent) / 100f)
}

/** Checks for a font file picked in Settings; the real test (loading it as a typeface) happens on the device. */
object CustomFontFile {
    const val LEGACY_NAME = "custom-font.ttf"

    /** Only a filename generated by the store may select a file inside the fonts directory. */
    fun storageName(name: String?): String = name?.takeIf {
        it.matches(Regex("font-[0-9a-f-]{36}\\.ttf"))
    } ?: LEGACY_NAME

    enum class Verdict { Ok, TooLarge, Empty, NotAFont }

    /** [size] in bytes and the first bytes of the file. */
    fun check(size: Long, header: ByteArray): Verdict = when {
        size <= 0L -> Verdict.Empty
        size > Limits.MAX_CUSTOM_FONT_BYTES -> Verdict.TooLarge
        !looksLikeFont(header) -> Verdict.NotAFont
        else -> Verdict.Ok
    }

    /** TrueType (0x00010000, `true`), OpenType/CFF (`OTTO`) or a collection (`ttcf`). */
    fun looksLikeFont(header: ByteArray): Boolean {
        if (header.size < 4) return false
        val tag = String(header, 0, 4, Charsets.ISO_8859_1)
        return tag == "OTTO" || tag == "true" || tag == "ttcf" ||
            (header[0].toInt() == 0 && header[1].toInt() == 1 && header[2].toInt() == 0 && header[3].toInt() == 0)
    }
}
