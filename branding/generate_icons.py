#!/usr/bin/env python3
"""Regenerates the Android launcher icon from branding/logo.png.

The logo is a square image of artwork on a plain rounded card; anything outside the card (black or
transparent corners) is ignored. Produces adaptive-icon layers in app/src/main/res:
  mipmap-*/ic_launcher_foreground.png  full-bleed card colour with the artwork centred in the safe zone
  mipmap-*/ic_launcher_monochrome.png  the dark outlines only, for themed icons
  values/ic_launcher_background.xml    the card colour

Usage: python3 branding/generate_icons.py   (needs Pillow)
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "branding" / "logo.png"
RES = ROOT / "app" / "src" / "main" / "res"

# Artwork width as a fraction of the 108dp layer. The launcher mask keeps the central 72dp and the
# guaranteed-visible circle is 66dp; the art is roughly square, so ~0.54 keeps it inside the circle.
ART_FRACTION = 0.54
DENSITIES = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
OUTLINE_MAX_LUMA = 90  # pixels darker than this count as outline for the monochrome layer


def main() -> None:
    logo = Image.open(LOGO).convert("RGBA")
    w, h = logo.size
    card = logo.getpixel((w // 2, h // 20))[:3]

    # Find the card: the bounding box of card-coloured pixels.
    rgb = logo.convert("RGB")
    px = rgb.load()

    def card_like(c) -> bool:
        return sum(abs(c[i] - card[i]) for i in range(3)) <= 40

    card_mask = Image.new("L", rgb.size, 0)
    cm = card_mask.load()
    for y in range(h):
        for x in range(w):
            if card_like(px[x, y]):
                cm[x, y] = 255
    c_left, c_top, c_right, c_bottom = card_mask.getbbox()

    # Artwork = non-card pixels inside the card's (inset) rounded rectangle, so the card's own
    # edge and whatever surrounds it never count as art.
    inset = (c_right - c_left) // 25
    radius = (c_right - c_left) // 5
    inside = Image.new("L", rgb.size, 0)
    ImageDraw.Draw(inside).rounded_rectangle(
        (c_left + inset, c_top + inset, c_right - inset, c_bottom - inset), radius=radius, fill=255
    )
    ip = inside.load()
    art_mask = Image.new("L", rgb.size, 0)
    am = art_mask.load()
    for y in range(h):
        for x in range(w):
            if ip[x, y] and not card_like(px[x, y]):
                am[x, y] = 255
    left, top, right, bottom = art_mask.getbbox()
    margin = (c_right - c_left) // 100
    # Paint everything outside the card in the card colour so no corner slivers survive the crop:
    # flood the dark surroundings (including the anti-aliased card edge) from the image corners.
    luma = rgb.convert("L")
    for corner in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        if luma.getpixel(corner) < 200:
            ImageDraw.floodfill(luma, corner, 255, thresh=200)
            ImageDraw.floodfill(rgb, corner, card, thresh=200 * 3)
    art = rgb.crop((left - margin, top - margin, right + margin, bottom + margin))

    # Centre the art on a square card-coloured canvas sized so it fills ART_FRACTION.
    side = round(max(art.size) / ART_FRACTION)
    canvas = Image.new("RGB", (side, side), card)
    canvas.paste(art, ((side - art.width) // 2, (side - art.height) // 2))

    # Monochrome: white where the outlines are, transparent elsewhere (the system tints it).
    luma = canvas.convert("L")
    mono = Image.new("RGBA", canvas.size, (255, 255, 255, 0))
    mono.putalpha(luma.point(lambda v: 255 if v < OUTLINE_MAX_LUMA else 0))

    for density, px in DENSITIES.items():
        out = RES / f"mipmap-{density}"
        out.mkdir(parents=True, exist_ok=True)
        canvas.resize((px, px), Image.LANCZOS).save(out / "ic_launcher_foreground.png", optimize=True)
        mono.resize((px, px), Image.LANCZOS).save(out / "ic_launcher_monochrome.png", optimize=True)

    (RES / "values" / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by branding/generate_icons.py -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">#FF{card[0]:02X}{card[1]:02X}{card[2]:02X}</color>\n'
        "</resources>\n"
    )
    print(f"card colour #{card[0]:02X}{card[1]:02X}{card[2]:02X}, art {art.size}, canvas {side}px")


if __name__ == "__main__":
    main()
